from datetime import datetime
from pathlib import Path
from typing import Any, Dict

from docx import Document

from create_review_plan.state import GenericAgentState


def _persist_policy_update(policy_file_path: str, new_rule: str) -> None:
    """
    Writes an approved human rule update back to the actual policy file
    on disk, so it persists across runs -- not just for the rest of the
    current graph execution.
    """

    if not policy_file_path:
        return

    path = Path(policy_file_path)
    if not path.is_file():
        return

    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M")
    entry_text = f"[Human-approved update, {timestamp}] {new_rule}"

    if path.suffix.lower() == ".docx":
        doc = Document(str(path))

        heading_text = "Human-Approved Policy Updates"
        has_heading = any(
            p.text.strip() == heading_text for p in doc.paragraphs
        )
        if not has_heading:
            # Don't rely on a named style like "Heading 1" -- not every
            # docx (especially ones generated by simple scripts) has
            # that style registered, and add_heading() raises a KeyError
            # if it's missing. A manually bolded paragraph works on any
            # docx regardless of its style definitions.
            heading_paragraph = doc.add_paragraph()
            heading_run = heading_paragraph.add_run(heading_text)
            heading_run.bold = True

        doc.add_paragraph(entry_text)
        doc.save(str(path))

    else:
        with open(path, "a", encoding="utf-8") as f:
            f.write(f"\n\n{entry_text}")


def update_policy(state: GenericAgentState) -> Dict[str, Any]:
    intervention = state.get("human_intervention") or {}
    new_rule = intervention.get("proposed_rule_text")

    current_policy = state.get("active_policy", "")
    if new_rule:
        updated_policy = f"{current_policy}\n\n[Human-approved update] {new_rule}".strip()
        _persist_policy_update(state.get("policy_file_path", ""), new_rule)
    else:
        updated_policy = current_policy

    return {"active_policy": updated_policy}